  Array.from({ length: n }, (_, i) => {
    const a = (i / n) * Math.PI * 2
    const cx = x + Math.cos(a) * 70 + (i % 2) * 18, cy = y + Math.sin(a) * 42
    return `<rect x="${cx - 32}" y="${cy - 26}" width="64" height="52" rx="16" fill="${i % 2 ? fill2 : fill}" transform="rotate(${(i * 37) % 90} ${cx} ${cy})"/>`
  }).join("") + `<circle cx="${x}" cy="${y}" r="24" fill="${fill}"/>
  <circle cx="${x - 40}" cy="${y - 50}" r="9" fill="${C.leaf}"/><circle cx="${x + 70}" cy="${y + 50}" r="9" fill="${C.leaf}"/>
  <circle cx="${x + 30}" cy="${y - 60}" r="7" fill="${C.chilli}"/>`

