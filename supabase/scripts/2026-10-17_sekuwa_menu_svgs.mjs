// One-off: give every photoless dish of a tenant a designed SVG placeholder
// (uploaded to Storage `menu-images/{tenant}/{item}.svg`, same path scheme as
// `uploadItemImage`), so new menu rows don't sit on the grey monogram until the
// owner photographs them. Re-uploading a real photo from /menu overwrites the
// `image_url` and leaves this file orphaned, which is fine.
//
//   node supabase/scripts/2026-10-17_sekuwa_menu_svgs.mjs <tenant_id> [--all]
//
// Needs SUPABASE_SERVICE_ROLE_KEY + NEXT_PUBLIC_SUPABASE_URL in .env.local.
// Default: only dishes whose image_url is null. --all: also replace existing
// placeholders generated by this script (URLs ending in .svg); never a real photo.

import { readFileSync } from "node:fs"
import { createClient } from "@supabase/supabase-js"

const env = Object.fromEntries(
  readFileSync(new URL("../../.env.local", import.meta.url), "utf8")
    .split("\n")
    .filter((l) => l.includes("=") && !l.startsWith("#"))
    .map((l) => [l.slice(0, l.indexOf("=")).trim(), l.slice(l.indexOf("=") + 1).trim().replace(/^"|"$/g, "")]),
)
const tenant = process.argv[2]
const all = process.argv.includes("--all")
if (!tenant) throw new Error("usage: <tenant_id> [--all]")

const sb = createClient(env.NEXT_PUBLIC_SUPABASE_URL, env.SUPABASE_SERVICE_ROLE_KEY, {
  auth: { persistSession: false },
})

// --- palette (warm, matches the printed menu) --------------------------------
const C = {
  bg1: "#fbf5ea", bg2: "#f3e6d2", ink: "#2b1d12", accent: "#c8571b", accent2: "#e3903a",
  plate: "#ffffff", plateRim: "#e8dcc6", meat: "#8a3b1c", meat2: "#b2552a", char: "#3b2a20",
  green: "#3f7d3a", leaf: "#6aa84f", noodle: "#e9b94d", broth: "#d98a3a", glass: "#cfe5ec",
  bottle: "#3a5a40", bottle2: "#8c6b3c", egg: "#f6e7c1", yolk: "#f2b632", chilli: "#c62828",
}

function esc(s) {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;")
}

// Two-line word wrap for the caption.
function wrap(name, max = 22) {
  const words = name.split(/\s+/)
  const lines = [""]
  for (const w of words) {
    const cur = lines[lines.length - 1]
    if ((cur + " " + w).trim().length > max && cur) lines.push(w)
    else lines[lines.length - 1] = (cur + " " + w).trim()
  }
  return lines.slice(0, 2)
}

