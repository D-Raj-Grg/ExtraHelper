// --- pick a family from the dish name ---------------------------------------
function art(name) {
  const n = name.toLowerCase()
  const x = 400, y = 250
  if (/coal|hukkha|hookah/.test(n)) return coal(x, y)
  if (/hot water/.test(n)) return cup(x, y)
  if (/sprite|coke|fanta|xtreme|red bull|lassi|water$/.test(n)) return glassSoda(x, y, /sprite/.test(n) ? "#cfead8" : /xtreme|red bull/.test(n) ? "#f2c66d" : "#e7e2d6")
  if (/wine/.test(n)) return bottle(x, y, "#5c1a2b", "WINE")
  if (/beer|barahsinghe|tuborg|gorkha/.test(n)) return bottle(x, y, C.bottle, "BEER")
  if (/rum|vodka|whisky|durbar|signature|ruslan|8848|old monk|khukuri/.test(n)) return bottle(x, y, C.bottle2, name.toUpperCase().slice(0, 11))
  if (/momo/.test(n)) return momo(x, y)
  if (/egg/.test(n) && !/wai wai|current|noodle/.test(n)) return plate(x, y, eggs(x, y - 10))
  if (/wai wai|current|noodle|chowmein/.test(n)) return bowl(x, y)
  if (/khaja|thali/.test(n)) return thali(x, y)
  if (/sekuwa|tass|choila|sukuti|bhutan/.test(n)) return plate(x, y, skewer(x, y - 10, 12))
  if (/pakoda|paneer|soyabean|prawn|papad|peanut|aalu|salad|fry|fries/.test(n) && !/chicken|buff|pork|mutton/.test(n))
    return plate(x, y, chunks(x, y - 5, 6, C.noodle, C.accent2))
  return plate(x, y, chunks(x, y - 5, 6, C.meat, C.meat2))
}

// Veg mark: circle vs triangle carries the meaning, colour only reinforces.
function vegMark(isVeg) {
  if (isVeg === null || isVeg === undefined) return ""
  const col = isVeg ? C.green : C.meat
  const inner = isVeg
    ? `<circle cx="60" cy="60" r="14" fill="${col}"/>`
    : `<path d="M60 44 L76 72 L44 72 Z" fill="${col}"/>`
  return `<rect x="36" y="36" width="48" height="48" rx="6" fill="#fff" stroke="${col}" stroke-width="4"/>${inner}`
}

function svg(item) {
  const lines = wrap(item.name)
  const fs = lines.length > 1 ? 40 : 46
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 800 600" width="800" height="600" role="img" aria-label="${esc(item.name)}">
  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="${C.bg1}"/><stop offset="1" stop-color="${C.bg2}"/></linearGradient>
    <radialGradient id="glow" cx=".5" cy=".42" r=".55"><stop offset="0" stop-color="#fff" stop-opacity=".9"/><stop offset="1" stop-color="#fff" stop-opacity="0"/></radialGradient>
  </defs>
  <rect width="800" height="600" fill="url(#bg)"/>
  <rect width="800" height="600" fill="url(#glow)"/>
  <rect x="18" y="18" width="764" height="564" rx="18" fill="none" stroke="${C.accent2}" stroke-width="3" opacity=".55"/>
  ${art(item.name)}
  ${vegMark(item.is_veg)}
  <rect x="0" y="470" width="800" height="130" fill="${C.ink}" opacity=".92"/>
  ${lines.map((l, i) => `<text x="400" y="${lines.length > 1 ? 520 + i * 46 : 545}" text-anchor="middle" font-family="Georgia, 'Times New Roman', serif" font-weight="700" font-size="${fs}" fill="${C.bg1}">${esc(l)}</text>`).join("")}
  <text x="400" y="455" text-anchor="middle" font-family="Helvetica, Arial, sans-serif" font-size="16" letter-spacing="4" fill="${C.accent}">THE SEKUWA STATION</text>
</svg>`
}

// --- run ---------------------------------------------------------------------
let q = sb.from("menu_items").select("id, name, is_veg, image_url").eq("tenant_id", tenant).order("name")
q = all ? q.or("image_url.is.null,image_url.ilike.%.svg%") : q.is("image_url", null)
const { data: items, error } = await q
if (error) throw error
console.log(`${items.length} dish(es) to draw`)

for (const it of items) {
  const path = `${tenant}/${it.id}.svg`
  const { error: upErr } = await sb.storage
    .from("menu-images")
    .upload(path, Buffer.from(svg(it)), { upsert: true, contentType: "image/svg+xml", cacheControl: "3600" })
  if (upErr) throw new Error(`${it.name}: ${upErr.message}`)
  const { data: pub } = sb.storage.from("menu-images").getPublicUrl(path)
  const url = `${pub.publicUrl}?v=${Date.now()}`
  const { error: dbErr } = await sb.from("menu_items").update({ image_url: url }).eq("id", it.id).eq("tenant_id", tenant)
  if (dbErr) throw new Error(`${it.name}: ${dbErr.message}`)
  console.log("✓", it.name)
}
